// Vercel only packages the files inside api/ plus what it can trace, so imports
// from src/ were missing at runtime. Bundle the handler into one self contained
// file. The output is committed so Vercel finds the function before any build.
import { build } from 'esbuild'

await build({
  entryPoints: ['server/streamers.ts'],
  outfile: 'api/streamers.js',
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node22',
  legalComments: 'none',
  banner: {
    js: '// Generated by scripts/build-api.mjs from server/streamers.ts. Do not edit.'
  }
})

console.log('api/streamers.js generado.')
